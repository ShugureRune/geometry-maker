import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('single click selects text; corners resize; rotation handle drags; double click edits; exports stay clean',async({page})=>{
 await page.goto('./');
 const seed=await page.getByTestId('current-seed').textContent();
 await page.getByRole('button',{name:'プレビューに文字を追加'}).click();
 const quick=page.getByRole('group',{name:'プレビュー上で文字を編集'});
 await quick.getByLabel('文字の内容').fill('選択して拡大');
 await quick.getByLabel('サイズ').fill('94');
 await quick.getByRole('button',{name:'編集を終了'}).click();
 const svg=page.getByTestId('preview');
 const title=svg.getByTestId('text-overlay').locator('text').last();
 const titleBox=await title.boundingBox();
 if(!titleBox)throw new Error('Title not visible');
 await page.mouse.click(titleBox.x+titleBox.width/2,titleBox.y+titleBox.height/2);
 const selection=page.getByTestId('text-selection');
 await expect(selection).toBeVisible();
 await expect(selection.locator('[data-handle^="resize"]')).toHaveCount(4);
 await expect(selection.getByTestId('text-rotate-handle')).toBeVisible();
 const originalSize=Number(await title.getAttribute('font-size'));
 const se=await selection.getByTestId('resize-se').boundingBox();
 if(!se)throw new Error('No resize handle');
 await page.mouse.move(se.x+se.width/2,se.y+se.height/2);
 await page.mouse.down();
 await page.mouse.move(se.x+se.width/2+75,se.y+se.height/2+45,{steps:8});
 await page.mouse.up();
 await expect.poll(async()=>Number(await title.getAttribute('font-size'))).toBeGreaterThan(originalSize);
 const resized=await title.boundingBox();
 if(!resized)throw new Error('No text after resize');
 await page.mouse.move(resized.x+resized.width/2,resized.y+resized.height/2);
 await page.mouse.down();
 await page.mouse.move(resized.x+resized.width/2+65,resized.y+resized.height/2-25,{steps:6});
 await page.mouse.up();
 await expect(selection).toBeVisible();
 const knob=await selection.getByTestId('text-rotate-handle').boundingBox();
 if(!knob)throw new Error('No rotate handle');
 const beforeAngle=await title.locator('xpath=..').getAttribute('transform');
 await page.mouse.move(knob.x+knob.width/2,knob.y+knob.height/2);
 await page.mouse.down();
 await page.mouse.move(knob.x+knob.width/2+45,knob.y+knob.height/2+10,{steps:7});
 await page.mouse.up();
 const afterAngle=await title.locator('xpath=..').getAttribute('transform');
 expect(afterAngle).not.toBe(beforeAngle);
 const pos=await title.boundingBox();
 if(!pos)throw new Error('Rotated title missing');
 await page.mouse.dblclick(pos.x+pos.width/2,pos.y+pos.height/2);
 const inline=page.getByTestId('inline-text-editor');
 await expect(inline).toBeVisible();
 await inline.getByLabel('文字をその場で編集').fill('編集成功\n2行目');
 await inline.getByLabel('文字をその場で編集').press('ControlOrMeta+Enter');
 await expect(svg.getByTestId('text-overlay')).toContainText('編集成功');
 await expect(page.getByTestId('current-seed')).toHaveText(seed??'');
 const nav=page.getByRole('navigation',{name:'設定カテゴリー'});
 await nav.getByRole('button',{name:'書き出し',exact:true}).click();
 const jsonPending=page.waitForEvent('download');
 await page.getByRole('button',{name:'作品の設定を保存'}).click();
 const json=JSON.parse((await readFile((await (await jsonPending).path())!)).toString());
 expect(json.textOverlay.text).toBe('編集成功\n2行目');
 expect(json.textOverlay.fontSize).toBeGreaterThan(originalSize);
 expect(json.textOverlay.rotation).not.toBe(0);
 const svgPending=page.waitForEvent('download');
 await page.getByRole('button',{name:'SVGを書き出す'}).click();
 const exported=await readFile((await (await svgPending).path())!,'utf8');
 expect(exported).toContain('編集成功');
 expect(exported).not.toContain('text-selection-border');
 expect(exported).not.toContain('preview-inline-editor');
});

test('hold-to-rotate continues only while pressed; arrows move and delete hides a selected title',async({page})=>{
 await page.goto('./');
 await page.getByRole('button',{name:'プレビューに文字を追加'}).click();
 await page.getByRole('group',{name:'プレビュー上で文字を編集'}).getByRole('button',{name:'編集を終了'}).click();
 const title=page.getByTestId('preview').getByTestId('text-overlay').locator('text').last();
 const rect=await title.boundingBox();
 if(!rect)throw new Error('title missing');
 await page.mouse.click(rect.x+rect.width/2,rect.y+rect.height/2);
 const knob=await page.getByTestId('text-rotate-handle').boundingBox();
 if(!knob)throw new Error('rotation handle missing');
 await page.mouse.move(knob.x+knob.width/2,knob.y+knob.height/2);
 await page.mouse.down();
 await page.waitForTimeout(900);
 const during=await title.locator('xpath=..').getAttribute('transform');
 expect(during).not.toContain('rotate(0 ');
 await page.mouse.up();
 const held=await title.locator('xpath=..').getAttribute('transform');
 await page.waitForTimeout(240);
 expect(await title.locator('xpath=..').getAttribute('transform')).toBe(held);
 const x=Number(await title.getAttribute('x'));
 await page.keyboard.press('ArrowRight');
 await expect.poll(async()=>Number(await title.getAttribute('x'))).toBeGreaterThan(x);
 await page.keyboard.press('Delete');
 await expect(page.getByTestId('preview').getByTestId('text-overlay')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'プレビューに文字を追加'})).toBeVisible();
});

test('mobile touch can select, resize a corner and double-tap to edit',async({browser})=>{
 const context=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:844},deviceScaleFactor:1});
 try{
  const page=await context.newPage();
  await page.goto('http://127.0.0.1:5173/');
  await page.getByLabel('キャンバスの比率').selectOption('9:16');
  await page.getByRole('button',{name:'プレビューに文字を追加'}).click();
  const quick=page.getByRole('group',{name:'プレビュー上で文字を編集'});
  await quick.getByLabel('文字の内容').fill('ネオン');
  await quick.getByLabel('サイズ').fill('65');
  await quick.getByRole('button',{name:'編集を終了'}).click();
  const title=page.getByTestId('preview').getByTestId('text-overlay').locator('text').last();
  const rect=await title.boundingBox();
  if(!rect)throw new Error('mobile text missing');
  await page.touchscreen.tap(rect.x+rect.width/2,rect.y+rect.height/2);
  const selection=page.getByTestId('text-selection');
  await expect(selection).toBeVisible();
  const se=await selection.getByTestId('resize-se').boundingBox();
  if(!se)throw new Error('touch corner missing');
  const original=Number(await title.getAttribute('font-size'));
  const x=se.x+se.width/2,y=se.y+se.height/2;
  const cdp=await context.newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y,id:1}]});
  for(let n=1;n<=7;n++)await cdp.send('Input.dispatchTouchEvent',{
   type:'touchMove',touchPoints:[{x:x+n*7,y:y+n*6,id:1}]
  });
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect.poll(async()=>Number(await title.getAttribute('font-size'))).toBeGreaterThan(original);
  const resized=await title.boundingBox();
  if(!resized)throw new Error('resized mobile text missing');
  const cx=resized.x+resized.width/2,cy=resized.y+resized.height/2;
  await page.touchscreen.tap(cx,cy);
  await page.touchscreen.tap(cx,cy);
  const inline=page.getByTestId('inline-text-editor');
  await expect(inline).toBeVisible();
  await inline.getByLabel('文字をその場で編集').fill('タップで編集成功');
  await inline.getByLabel('文字をその場で編集').press('ControlOrMeta+Enter');
  await expect(page.getByTestId('preview').getByTestId('text-overlay')).toContainText('タップで編集成功');
 }finally{await context.close();}
});
