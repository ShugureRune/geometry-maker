  'uniform int uMode;',
  'uniform float uTime;',
  'uniform float uSeed;',
  'uniform float uIntensity;',
  'uniform float uDensity;',
  'uniform float uLow;',
  'uniform float uOutdoorFog;',
  'uniform float uWorldHour;',
  'uniform float uWorldSun;',
  'uniform float uWorldStorm;',
  'uniform float uCustomColor;',
  'uniform vec3 uSkyBase;',
  'uniform vec3 uSkyAccent;',
  'uniform vec3 uSkyHighlight;',
  'uniform sampler2D uGlyphAtlas;',
  'varying vec3 vRay;',
  '#define PI 3.141592653589793',
  'float hash21(vec2 p){',
  '  p+=vec2(uSeed*17.1,uSeed*53.3);',
  '  return fract(sin(dot(p,vec2(127.1,311.7)))*43758.5453123);',
  '}',
  'float noise2(vec2 p){',
  '  vec2 i=floor(p),f=fract(p);',
  '  f=f*f*(3.0-2.0*f);',
  '  return mix(mix(hash21(i),hash21(i+vec2(1.0,0.0)),f.x),',
  '    mix(hash21(i+vec2(0.0,1.0)),hash21(i+vec2(1.0,1.0)),f.x),f.y);',
  '}',
  'float fbm(vec2 p){',
  '  float v=0.0,a=0.5;',
  '  for(int i=0;i<4;i++){',
  '    if(uLow>.5 && i>=2)break;',
  '    v+=a*noise2(p);p=p*2.03+vec2(2.7,1.3);a*=0.5;',
  '  }',
  '  return v;',
  '}',
  'float stars(vec2 uv,float factor){',
  '  if(factor<=0.0)return 0.0;',
  '  vec2 p=uv*vec2(470.0,235.0)*(.55+.65*factor);',
  '  vec2 cell=floor(p),f=fract(p)-.5;',
  '  float present=step(1.0-.014*min(2.0,factor),hash21(cell));',
  '  float radius=.12+.07*hash21(cell+23.1);',
  '  float aa=max(.045,.5*length(fwidth(p)));',
  '  float dotShape=1.0-smoothstep(radius,radius+aa,length(f));',
  '  float twinkle=.72+.28*sin(uTime*2.4+hash21(cell+8.3)*20.0);',
  '  return present*dotShape*twinkle;',
  '}',
  'void main(){',
  '  vec3 d=normalize(vRay);',
  '  float lon=atan(d.x,-d.z);',
  '  vec2 uv=vec2(lon/(2.0*PI)+.5,asin(clamp(d.y,-1.0,1.0))/PI+.5);',
  '  float t=uTime;',
  '  float gain=clamp(uIntensity,0.0,2.0);',
  '  float density=clamp(uDensity,0.0,2.0);',
